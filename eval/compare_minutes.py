"""Addendum A13: durations said in minutes. vad-think-combo against vad-think-combo-minutes (no model calls).

A slip: a reply text of the model that says 一个半小时 (or 一个半个小时, "an hour and a half", "1.5 hours") in an
item-run whose tool record has no 90-minute meeting. Counted per item-run (an item-run with two such texts counts
once). Duration wording: every reply text that mentions a duration, said in minutes only or not.

  python -X utf8 eval/compare_minutes.py [<arm> ...]  -> eval/results/minutes_vs_combo.md
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "eval" / "results"
ARMS = ["vad-think-combo", "vad-think-combo-minutes", *sys.argv[1:]]   # more arms as arguments (A14)
GROUPS = {"42 items, run1 + run2": ["run1", "run2"],
          "T07, N06, T09, T14 repeated, min1 to min5": [f"min{i}" for i in range(1, 6)]}
FOCUS = ["T07", "N06", "T09", "T14"]
SLIP = re.compile(r"一个半(个)?小时|an hour and a half|one and a half hours|1\.5 hours", re.I)
DUR = re.compile(r"分钟|小时|minute|hour", re.I)
MIN_ONLY = re.compile(r"分钟|minute", re.I)
HOURS = re.compile(r"小时|hour", re.I)


def traces(folder, arm):
    f = RES / folder / f"{arm}.jsonl"
    if not f.exists():
        return []
    return [json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()]


def texts(t):
    return [st["text"] for r in t.get("responses", []) for st in r.get("steps", [])
            if st.get("kind") == "llm" and st.get("text", "").strip()]


def slipped(t):
    has90 = any(c.get("args", {}).get("duration_minutes") == 90 for c in t.get("tool_log", []))
    return [x for x in texts(t) if SLIP.search(x)] if not has90 else []


def main():
    out = ["# Durations said in minutes (generated by eval/compare_minutes.py)", "",
           "Rules: eval/PREREGISTRATION.md addendum A13. A slip is a reply text that says 一个半小时 (90 minutes) in an "
           "item-run whose tools booked no 90-minute meeting; counted once per item-run.", ""]
    rows = []
    for group, folders in GROUPS.items():
        out += [f"## {group}", "",
                "| Arm | Item-runs | On T07, N06, T09, T14 | Slips there | Slips on other items | Texts with a duration | "
                "Said in minutes only | Errors |", "|---|---|---|---|---|---|---|---|"]
        for arm in ARMS:
            ts = [(fo, t) for fo in folders for t in traces(fo, arm)]
            if not ts:
                out.append(f"| {arm} | NOT RUN | | | | | | |")
                continue
            focus = [(fo, t) for fo, t in ts if t["item"] in FOCUS]
            s_focus = [(fo, t) for fo, t in focus if slipped(t)]
            s_other = [(fo, t) for fo, t in ts if t["item"] not in FOCUS and slipped(t)]
            dur = [x for _, t in ts for x in texts(t) if DUR.search(x)]
            mins = [x for x in dur if MIN_ONLY.search(x) and not HOURS.search(x)]
            errs = sum("error" in t for _, t in ts)
            out.append(f"| {arm} | {len(ts)} | {len(focus)} | {len(s_focus)} | {len(s_other)} | {len(dur)} | "
                       f"{len(mins)} ({100 * len(mins) / len(dur):.0f}%) | {errs} |" if dur else
                       f"| {arm} | {len(ts)} | {len(focus)} | {len(s_focus)} | {len(s_other)} | 0 | - | {errs} |")
            for fo, t in s_focus + s_other:
                for x in slipped(t):
                    rows.append((group, fo, arm, t["item"], x))
        out.append("")
    out += ["## Every slip", "", "| Group | Run | Arm | Item | What the model wrote |", "|---|---|---|---|---|"]
    out += [f"| {g} | {fo} | {a} | {i} | {x.replace('|', '/')} |" for g, fo, a, i, x in rows] or ["| none | | | | |"]
    (RES / "minutes_vs_combo.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
