"""Tables for the report, from eval/results/run1 and run2 scores (run score.py first).

  python -X utf8 eval/tables.py  -> eval/results/summary.md and eval/results/failures.json
Attribution follows the order fixed in PREREGISTRATION.md.
"""
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "eval" / "results"
RUNS = ["run1", "run2"]
ARMS = ["vad", "smart", "vad-think", "oracle"]
AUDIO = ["vad", "smart", "vad-think"]
PRICE_IN, PRICE_OUT = 0.10, 0.50   # USD per million tokens, claude-haiku-5-5


def load():
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {}
    for r in RUNS:
        for a in ARMS:
            f = RES / r / f"{a}.jsonl"
            tr[(r, a)] = {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}
    return sc, tr


def med(xs):
    return round(st.median(xs), 2) if xs else None


def pctl(xs, q):
    xs = sorted(xs)
    if not xs:
        return None
    k = (len(xs) - 1) * q
    lo = int(k)
    hi = min(lo + 1, len(xs) - 1)
    return round(xs[lo] + (xs[hi] - xs[lo]) * (k - lo), 2)


def strict(r):
    return bool(r["task_pass"]) and r.get("interaction_pass") in (True, None)


def attribute(r, tr_item, oracle_rows):
    """One cause per failed item-run, rules in the preregistered order."""
    if "harness_error" in r:
        return "HARNESS"
    cid = r["item"]
    ic = r.get("interaction", {})
    steps = [s for resp in tr_item.get("responses", []) for s in resp["steps"] if s["kind"] == "tool"]
    segs = tr_item.get("user_segments", [])
    inter = next((s for s in segs if s["role"] == "interrupt"), None)
    mut = {"create_meeting", "update_meeting", "cancel_meeting", "set_reminder"}
    if inter and any(s["name"] in mut and s["start"] < inter["start"] and not s["result"].startswith('{"error"')
                     for s in steps) and r["cat"] == "interrupt" and not r["task_pass"]:
        return "COMMITTED"
    if ic.get("kept_talking") is False or ic.get("stopped") is False or ic.get("quiet_after") is False:
        return "BARGE-IN"
    if r["noise"] == "babble" and any(e["ev"] == "forced_endpoint" for e in tr_item.get("events", [])):
        return "NOISE-VAD"
    if r["cat"] == "pause" and (r.get("premature_llm") or ic.get("no_takeover_in_pause") is False):
        if ic.get("no_takeover_in_pause") is False or not r["task_pass"]:
            return "ENDPOINT"
    oracle_pass = any(o["task_pass"] for o in oracle_rows.get(cid, []))
    slots = r.get("slots", {})
    if slots and not slots.get("all", True) and oracle_pass:
        return "ASR"
    if not oracle_pass or slots.get("all", True):
        return "MODEL"
    return "OTHER"


def main():
    sc, tr = load()
    out = ["# Results tables (generated by eval/tables.py)", ""]
    # ---------- headline ----------
    out += ["## Pass counts (of 42) per run", "", "| Arm | Run | Task | Interaction | Strict | Reasoning said aloud |",
            "|---|---|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            rows = sc[r][a]
            inter = [x["interaction_pass"] for x in rows if x.get("interaction_pass") is not None]
            out.append(f"| {a} | {r} | {sum(x['task_pass'] for x in rows)} | "
                       f"{sum(inter)}/{len(inter) if inter else 0} | {sum(strict(x) for x in rows)} | "
                       f"{sum(1 for x in rows if x.get('leak'))} |")
    # ---------- by category ----------
    cats = ["task", "pause", "interrupt", "backchannel", "noise-pink", "noise-babble"]
    out += ["", "## Strict pass by category (run1 + run2, so out of 2 x items)", "",
            "| Arm | " + " | ".join(cats) + " |", "|---|" + "---|" * len(cats)]
    for a in ARMS:
        cells = []
        for c in cats:
            n = k = 0
            for r in RUNS:
                for x in sc[r][a]:
                    key = x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"
                    if key == c:
                        n += 1
                        k += strict(x)
            cells.append(f"{k}/{n}")
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    out += ["", "Task pass only, same layout:", "", "| Arm | " + " | ".join(cats) + " |", "|---|" + "---|" * len(cats)]
    for a in ARMS:
        cells = []
        for c in cats:
            n = k = 0
            for r in RUNS:
                for x in sc[r][a]:
                    key = x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"
                    if key == c:
                        n += 1
                        k += bool(x["task_pass"])
            cells.append(f"{k}/{n}")
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    # ---------- latency ----------
    out += ["", "## Response latency, seconds (user stops talking -> agent audio), first turn of task, pause and noise items",
            "", "| Arm | Condition | n | First audio median | p90 | Answer audio median | Turn-end wait | ASR | Model (to first chunk) | Tools | TTS first chunk |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a in AUDIO:
        for cond in ["clean task", "pause", "pink", "babble"]:
            L = []
            for r in RUNS:
                for x in sc[r][a]:
                    if cond == "clean task" and x["cat"] != "task":
                        continue
                    if cond == "pause" and x["cat"] != "pause":
                        continue
                    if cond in ("pink", "babble") and x["noise"] != cond:
                        continue
                    for l in x.get("latency", []):
                        if l["role"] == "request" and l.get("first_audio") is not None:
                            L.append(l)
            if not L:
                continue
            f = [l["first_audio"] for l in L]
            ans = [l["answer_audio"] for l in L if l.get("answer_audio") is not None]
            out.append(f"| {a} | {cond} | {len(L)} | {med(f)} | {pctl(f, 0.9)} | {med(ans)} | "
                       f"{med([l['endpoint_wait'] for l in L])} | {med([l['asr'] for l in L])} | "
                       f"{med([l['llm'] for l in L])} | {med([l['tools'] for l in L])} | {med([l['tts'] for l in L])} |")
    # sensitivity: the same latencies if the speech steps had run at the full-load calibration
    cal = json.loads((ROOT / "eval" / "local_timing.json").read_text(encoding="utf-8"))
    lo = json.loads((ROOT / "eval" / "local_timing_loaded.json").read_text(encoding="utf-8"))

    def loaded_delta(l, arm):
        asr_secs = (l["asr"] - cal["asr"]["intercept"]) / cal["asr"]["slope"]
        tts_secs = (l["tts"] - cal["tts"]["intercept"]) / cal["tts"]["slope"]
        d = (lo["asr"]["intercept"] + lo["asr"]["slope"] * asr_secs - l["asr"]) + \
            (lo["tts"]["intercept"] + lo["tts"]["slope"] * tts_secs - l["tts"])
        if arm == "smart":
            d += lo["smart_turn"]["seconds"] - cal["smart_turn"]["seconds"]
        return d
    out += ["", "Sensitivity: first-audio median on clean task items if recognition, first speech chunk and one Smart Turn "
            "check had taken their full-load times (local_timing_loaded.json); a static re-estimate, the conversation is not re-simulated:", ""]
    for a in AUDIO:
        L = [l for r in RUNS for x in sc[r][a] if x["cat"] == "task" for l in x.get("latency", [])
             if l["role"] == "request" and l.get("first_audio") is not None]
        out.append(f"- {a}: {med([l['first_audio'] for l in L])} s as run, {med([l['first_audio'] + loaded_delta(l, a) for l in L])} s at full load")
    # per run medians (clean task)
    out += ["", "First-audio median on clean task items, per run:", ""]
    for a in AUDIO:
        vals = []
        for r in RUNS:
            f = [l["first_audio"] for x in sc[r][a] if x["cat"] == "task" for l in x.get("latency", [])
                 if l["role"] == "request" and l.get("first_audio") is not None]
            vals.append(f"{r} {med(f)} (n={len(f)})")
        out.append(f"- {a}: " + ", ".join(vals))
    # ---------- interruptions ----------
    out += ["", "## Interruptions and backchannels (run1 + run2)", "",
            "| Arm | Interrupt overlaps | Stopped | Stop latency median (s) | max | Quiet after stop (I03, I08) | Backchannel overlaps | Kept talking |",
            "|---|---|---|---|---|---|---|---|"]
    for a in AUDIO:
        io = st_ = q = qn = bo = kt = 0
        lat = []
        for r in RUNS:
            for x in sc[r][a]:
                if x["cat"] == "interrupt":
                    if x.get("overlap"):
                        io += 1
                        st_ += bool(x["interaction"].get("stopped"))
                        if "quiet_after" in x["interaction"]:
                            qn += 1
                            q += bool(x["interaction"]["quiet_after"])
                    if "stop_latency" in x:
                        lat.append(x["stop_latency"])
                if x["cat"] == "backchannel" and x.get("overlap"):
                    bo += 1
                    kt += bool(x["interaction"].get("kept_talking"))
        out.append(f"| {a} | {io}/16 | {st_}/{io} | {med(lat)} | {max(lat) if lat else None} | {q}/{qn} | {bo}/8 | {kt}/{bo} |")
    # ---------- pauses ----------
    out += ["", "## Pauses (run1 + run2, 12 item-runs per arm)", "",
            "| Arm | Turn end detected inside the pause | Agent audio inside the pause | Change made inside the pause | Task pass |",
            "|---|---|---|---|---|"]
    for a in AUDIO:
        rows = [x for r in RUNS for x in sc[r][a] if x["cat"] == "pause"]
        out.append(f"| {a} | {sum(bool(x.get('premature_llm')) for x in rows)} | "
                   f"{sum(x['interaction'].get('no_takeover_in_pause') is False for x in rows)} | "
                   f"{sum(bool(x.get('premature_mutation')) for x in rows)} | {sum(bool(x['task_pass']) for x in rows)} |")
    # ---------- babble ----------
    out += ["", "## Babble items (N05-N08, run1 + run2)", ""]
    for a in AUDIO:
        ts = [tr[(r, a)][i] for r in RUNS for i in ("N05", "N06", "N07", "N08")]
        out.append(f"- {a}: {sum(any(e['ev'] == 'forced_endpoint' for e in t['events']) for t in ts)} of {len(ts)} "
                   f"item-runs reached the 20 s cap; {sum(bool(t['barge_ins']) for t in ts)} of {len(ts)} had a barge-in")
    out += ["", "Reasoning said aloud, run1 + run2: " + ", ".join(
        f"{a} {sum(1 for r in RUNS for x in sc[r][a] if x.get('leak'))} of 84" for a in ARMS)]
    # ---------- smart turn ----------
    out += ["", "## Smart Turn decisions (smart arm, run1 + run2)", ""]
    checks = [c for r in RUNS for t in tr[(r, "smart")].values() for c in t.get("smart_checks", [])]
    probs = [c for c in checks if "p" in c]
    fb = [c for c in checks if c.get("fallback")]
    out.append(f"- {len(probs)} checks, {sum(c['p'] > 0.5 for c in probs)} judged complete, "
               f"{sum(c['p'] <= 0.5 for c in probs)} judged unfinished; {len(fb)} turns ended by the 3 s fallback; "
               f"median inference {med([c['dur'] for c in probs])} s")
    # ---------- ASR ----------
    asr = json.loads((RES / "asr_check.json").read_text(encoding="utf-8"))
    out += ["", "## Recognition only (exact user segments without backchannels, SenseVoice, ITN off)", "",
            "| Language / noise | Segments | Errors / tokens | Mixed error rate |", "|---|---|---|---|"]
    agg = {}
    for row in asr["rows"]:
        if row["role"] == "backchannel":
            continue
        a_ = agg.setdefault(f"{row['lang']} / {row['noise']}", [0, 0, 0])
        a_[0] += 1
        a_[1] += row["errors"]
        a_[2] += row["ref_tokens"]
    for k, v in sorted(agg.items()):
        out.append(f"| {k} | {v[0]} | {v[1]}/{v[2]} | {v[1] / max(1, v[2]):.1%} |")
    bc = [f"{row['item']} {row['ref']} -> {row['sensevoice_itn']}" for row in asr["rows"] if row["role"] == "backchannel"]
    out += ["", "Backchannels as recognized: " + "; ".join(bc)]
    out += ["", "Key words reaching the model (audio arms, run1 + run2): items where every key word was in the transcript", ""]
    for a in AUDIO:
        rows = [x for r in RUNS for x in sc[r][a] if x.get("slots") and x["slots"].get("missing") is not None]
        withslots = [x for x in rows if x["slots"]["missing"] or x["slots"]["all"]]
        out.append(f"- {a}: {sum(x['slots']['all'] for x in withslots)}/{len(withslots)}")
    # ---------- repeat agreement ----------
    out += ["", "## Run-to-run agreement (same item, strict pass equal in run1 and run2)", ""]
    for a in ARMS:
        r1 = {x["item"]: strict(x) for x in sc["run1"][a]}
        r2 = {x["item"]: strict(x) for x in sc["run2"][a]}
        same = sum(r1[k] == r2[k] for k in r1)
        diff = [k for k in r1 if r1[k] != r2[k]]
        out.append(f"- {a}: {same}/42 agree; differ on {', '.join(diff) if diff else 'none'}")
    # ---------- attribution ----------
    out += ["", "## Failure causes (strict failures, run1 + run2)", "", "| Arm | " + " | ".join(
        ["COMMITTED", "BARGE-IN", "NOISE-VAD", "ENDPOINT", "ASR", "MODEL", "OTHER", "HARNESS"]) + " |", "|---|" + "---|" * 8]
    fails = []
    oracle_rows = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            oracle_rows.setdefault(x["item"], []).append(x)
    for a in AUDIO:
        cnt = {}
        for r in RUNS:
            for x in sc[r][a]:
                if strict(x):
                    continue
                cause = attribute(x, tr[(r, a)][x["item"]], oracle_rows)
                cnt[cause] = cnt.get(cause, 0) + 1
                fails.append({"arm": a, "run": r, "item": x["item"], "cause": cause, "checks": x["checks"],
                              "interaction": x.get("interaction"), "slots_missing": x.get("slots", {}).get("missing"),
                              "asr": x.get("slots", {}).get("asr_texts"), "notes": x.get("notes")})
        out.append(f"| {a} | " + " | ".join(str(cnt.get(k, 0)) for k in
                   ["COMMITTED", "BARGE-IN", "NOISE-VAD", "ENDPOINT", "ASR", "MODEL", "OTHER", "HARNESS"]) + " |")
    ofails = [{"arm": "oracle", "run": r, "item": x["item"], "checks": x["checks"]} for r in RUNS for x in sc[r]["oracle"] if not x["task_pass"]]
    out += ["", f"Oracle task failures: {', '.join(sorted(set(f['item'] + '(' + f['run'] + ')' for f in ofails))) or 'none'}"]
    # ---------- cost ----------
    out += ["", "## Tokens and cost", "", "| Run | Arm | Calls | Input tokens | Output tokens | USD |", "|---|---|---|---|---|---|"]
    tot = 0.0
    for r in RUNS:
        for a in ARMS:
            u = json.loads((RES / r / f"{a}.usage.json").read_text(encoding="utf-8"))
            usd = u["input_tokens"] / 1e6 * PRICE_IN + u["output_tokens"] / 1e6 * PRICE_OUT
            tot += usd
            out.append(f"| {r} | {a} | {u['calls']} | {u['input_tokens']} | {u['output_tokens']} | {usd:.4f} |")
    out.append(f"| total | | | | | {tot:.4f} |")
    (RES / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (RES / "failures.json").write_text(json.dumps(fails + ofails, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
