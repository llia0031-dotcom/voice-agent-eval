"""Addendum A6: confirm before cancelling (vad-think-confirm) against vad-think.

Needs, scored first with score.py:
- the 42 items: results/run1, results/run2 (vad-think, vad-think-confirm, oracle);
- the four confirmation items: results/confirm1, results/confirm2 (vad-think, vad-think-confirm),
  scored with `score.py --cases eval/confirm_cases.json eval/results/confirm1 eval/results/confirm2`.

  python -X utf8 eval/compare_confirm.py  -> eval/results/confirm_vs_base.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, RUNS, attribute, med, strict  # noqa: E402

BASE, NEW = "vad-think", "vad-think-confirm"
ARMS = [BASE, NEW]
CRUNS = ["confirm1", "confirm2"]


def traces(folder, arm):
    f = RES / folder / f"{arm}.jsonl"
    return {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}


def scores(folder):
    return json.loads((RES / folder / "scores.json").read_text(encoding="utf-8"))["items"]


def cancels(t):
    """(time, response index) of every cancel_meeting that ran and did not return an error."""
    return [(s["start"], i) for i, r in enumerate(t["responses"]) for s in r["steps"]
            if s["kind"] == "tool" and s["name"] == "cancel_meeting" and not str(s["result"]).startswith('{"error"')]


def held(t):
    return [(s["start"], i) for i, r in enumerate(t["responses"]) for s in r["steps"] if s["kind"] == "held_tool"]


def reply_after(t, i):
    """Text of response i's last spoken step (what the agent said after holding a call)."""
    steps = [s for s in t["responses"][i]["steps"] if s["kind"] == "llm" and s["text"].strip()]
    return steps[-1]["text"].strip() if steps else ""


def cost(folder, arm):
    f = RES / folder / f"{arm}.usage.json"
    if not f.exists():
        return 0.0
    u = json.loads(f.read_text(encoding="utf-8"))
    return u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6


def main():
    sc = {r: scores(r) for r in RUNS}
    tr = {(r, a): traces(r, a) for r in RUNS for a in (*ARMS, "oracle")}
    out = ["# Confirm before cancelling: vad-think-confirm against vad-think (generated by eval/compare_confirm.py)", "",
           "Rules: eval/PREREGISTRATION.md addendum A6. Part 1: the 42 items, run1 + run2. Part 2: the four "
           "confirmation items in eval/confirm_cases.json, two runs (confirm1, confirm2), both arms.", "",
           "## Part 1: the 42 items", "", "| Arm | Run | Task | Interaction | Strict |", "|---|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            rows = sc[r][a]
            inter = [x["interaction_pass"] for x in rows if x.get("interaction_pass") is not None]
            out.append(f"| {a} | {r} | {sum(bool(x['task_pass']) for x in rows)} | {sum(inter)}/{len(inter)} | "
                       f"{sum(strict(x) for x in rows)} |")
    orc = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            orc.setdefault(x["item"], []).append(x)
    out += ["", "Items with a cancel request (strict pass; cause if failed):", "",
            "| Item | " + " | ".join(f"{a} {r}" for a in ARMS for r in RUNS) + " |", "|---|" + "---|" * 4]
    for iid in ["T04", "I05"]:
        cells = []
        for a in ARMS:
            for r in RUNS:
                x = next(x for x in sc[r][a] if x["item"] == iid)
                cells.append("pass" if strict(x) else attribute(x, tr[(r, a)][iid], orc))
        out.append(f"| {iid} | " + " | ".join(cells) + " |")

    out += ["", f"Every held call in the 42-item runs of {NEW}:", "",
            "| Run | Item | Held at (s) | What the agent said next | Cancel ran later? |", "|---|---|---|---|---|"]
    for r in RUNS:
        for iid, t in tr[(r, NEW)].items():
            for at, i in held(t):
                ran = [c for c in cancels(t) if c[1] > i]
                out.append(f"| {r} | {iid} | {at:.2f} | {reply_after(t, i)} | "
                           + (f"yes, at {ran[0][0]:.2f}" if ran else "no") + " |")

    out += ["", "Failed item-runs and their cause (preregistered order):", "", "| Arm | Run | Item | Cause |", "|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            for x in sc[r][a]:
                if not strict(x):
                    out.append(f"| {a} | {r} | {x['item']} | {attribute(x, tr[(r, a)][x['item']], orc)} |")

    out += ["", "## Part 2: the four confirmation items", "",
            "Asked first: no cancel ran before the user's answer began. Cancel time: seconds from the end of the request "
            "to the cancel that ran.", "",
            "| Arm | Run | Item | User's answer | Task pass | Cancel ran | Asked first | Cancel time (s) | What the agent said first |",
            "|---|---|---|---|---|---|---|---|---|"]
    summary = {a: {"pass": 0, "n": 0, "asked": 0, "times": []} for a in ARMS}
    for a in ARMS:
        for r in CRUNS:
            csc = {x["item"]: x for x in scores(r)[a]}
            for iid, t in traces(r, a).items():
                segs = {s["role"]: s for s in t["user_segments"]}
                ans = segs.get("answer")
                c = cancels(t)
                asked = not any(ans is None or at < ans["start"] for at, _ in c)
                when = round(c[0][0] - segs["request"]["end"], 2) if c else None
                first = reply_after(t, 0)
                summary[a]["pass"] += bool(csc[iid]["task_pass"])
                summary[a]["n"] += 1
                summary[a]["asked"] += asked
                if when is not None:
                    summary[a]["times"].append(when)
                out.append(f"| {a} | {r} | {iid} | {ans['text'] if ans else ''} | {'yes' if csc[iid]['task_pass'] else 'no'} | "
                           f"{'yes' if c else 'no'} | {'yes' if asked else 'no'} | {when if when is not None else ''} | {first} |")
    out += ["", "| Arm | Task pass | Asked first | Cancel time, median (s) |", "|---|---|---|---|"]
    for a in ARMS:
        s = summary[a]
        out.append(f"| {a} | {s['pass']} of {s['n']} | {s['asked']} of {s['n']} | {med(s['times'])} |")

    out += ["", f"Where the time goes in {NEW} (seconds; times are from the end of the request unless stated):", "",
            "| Run | Item | Question starts | Question lasts | Answer starts after the question | Turn end after the answer | "
            "Cancel after the turn end |", "|---|---|---|---|---|---|---|"]
    for r in CRUNS:
        for iid, t in traces(r, NEW).items():
            segs = {s["role"]: s for s in t["user_segments"]}
            q = [p for p in t["pieces"] if p["resp"] == 0 and p["end"] > p["start"]]
            qs, qe = min(p["start"] for p in q), max(p["end"] for p in q)
            r1 = t["responses"][1] if len(t["responses"]) > 1 else None
            c = cancels(t)
            out.append(f"| {r} | {iid} | {qs - segs['request']['end']:.2f} | {qe - qs:.2f} | "
                       f"{segs['answer']['start'] - qe:.2f} | "
                       + (f"{r1['t_endpoint'] - segs['answer']['end']:.2f}" if r1 else "") + " | "
                       + (f"{c[0][0] - r1['t_endpoint']:.2f}" if c and r1 else "no cancel") + " |")
    rows = [x for r in RUNS for x in sc[r][NEW]]
    it = [x for x in rows if x["cat"] == "interrupt" and x.get("overlap")]
    bc = [x for x in rows if x["cat"] == "backchannel" and x.get("overlap")]
    out += ["", f"Turn-taking in {NEW} on the 42 items (run1 + run2): interruptions stopped "
            f"{sum(bool(x['interaction'].get('stopped')) for x in it)} of {len(it)}, median stop latency "
            f"{med([x['stop_latency'] for x in it if 'stop_latency' in x])} s; backchannels talked through "
            f"{sum(bool(x['interaction'].get('kept_talking')) for x in bc)} of {len(bc)}."]

    c42 = sum(cost(r, NEW) for r in RUNS)
    cc = {a: sum(cost(r, a) for r in CRUNS) for a in ARMS}
    out += ["", f"Model cost: {NEW} on the 42 items, two runs: {c42:.3f} USD; the four confirmation items, two runs: "
            f"{cc[BASE]:.3f} USD ({BASE}) and {cc[NEW]:.3f} USD ({NEW}).", ""]
    (RES / "confirm_vs_base.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
