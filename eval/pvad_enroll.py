"""Speaker embedding of each item's first user utterance, for FireRedChat pVAD (needs torch and SpeechBrain, so it
runs in portfolio-local/maai-env):

  HF_HOME=<portfolio-local>/voice-models/hf  <maai-env python> -X utf8 eval/pvad_enroll.py
      -> eval/pvad_enroll.json, items of eval/cases.json
  ... eval/pvad_enroll.py --add confirm_cases      (or --add disfluent_cases)
      -> adds the items of eval/<stem>.json to that file; existing entries are not touched

As the FireRedChat LiveKit plugin does after the first utterance: ECAPA (speechbrain/spkrec-ecapa-voxceleb, the copy
shipped with the pVAD model) over at most the first 5 s (80000 samples) of the first utterance as the microphone
hears it, noise included, L2-normalised. Every item's first segment starts at a fixed time (0.8 s), so this does not
depend on a run. seconds_per_embedding_median is the compute time measured when the file was first written (the
time pipeline.py waits before setting the embedding); --add records its own timing under another key.
"""
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch
from speechbrain.inference.speaker import EncoderClassifier

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mic_rebuild import ROOT, SR, load, mic, segments  # noqa: E402
from config import MODELS  # noqa: E402

SNAP = (MODELS / "hf" / "hub" / "models--FireRedTeam--FireRedChat-pvad" / "snapshots"
        / "74561b17a50fbe9d8f84dacc453f175cb97f567c")
WINDOW = 80000
OUT = ROOT / "eval" / "pvad_enroll.json"


def embed(stem, ecapa):
    cases, man, noise = load(stem)
    starts = {c["id"]: c["segments"][0]["at"]["abs"] for c in cases["items"] if "segments" in c}
    out, secs = {}, []
    for iid in man["items"]:
        src = next((c for c in cases["items"] if c["id"] == iid), {})
        st = starts.get(iid) or starts[src["copy_of"]]
        first = segments(man, iid)[0]
        m, _ = mic(cases, man, noise, iid, [st], st + len(first) / SR + 0.1)
        a = m[int(st * SR): int(st * SR) + min(WINDOW, len(first))]
        t0 = time.perf_counter()
        e = ecapa.encode_batch(torch.from_numpy(a).unsqueeze(0))[0][0].detach()
        secs.append(time.perf_counter() - t0)
        out[iid] = [round(float(v), 6) for v in (e / e.norm(p=2, dim=0, keepdim=True)).numpy()]
    return out, secs


def main():
    ecapa = EncoderClassifier.from_hparams(source=str(SNAP / "spkrec-ecapa-voxceleb"),
                                           savedir=str(SNAP / "spkrec-ecapa-voxceleb"), run_opts={"device": "cpu"})
    if sys.argv[1:2] == ["--add"]:
        stem = sys.argv[2]
        doc = json.loads(OUT.read_text(encoding="utf-8"))
        new, secs = embed(stem, ecapa)
        assert not set(new) & set(doc["items"]), "item ids overlap"
        doc["items"].update(new)
        doc[f"seconds_per_embedding_median_{stem}"] = round(float(np.median(secs)), 3)
        OUT.write_text(json.dumps(doc), encoding="utf-8")
        print("added", len(new), "items")
        return
    out, secs = embed("cases", ecapa)
    OUT.write_text(json.dumps({
        "about": "ECAPA embedding (192 values, L2-normalised) of each item's first utterance as heard on the "
                 "microphone, at most 5 s; generated by eval/pvad_enroll.py",
        "seconds_per_embedding_median": round(float(np.median(secs)), 3), "items": out}), encoding="utf-8")
    print(len(out), "items; median", round(float(np.median(secs)), 3), "s per embedding")


if __name__ == "__main__":
    main()
