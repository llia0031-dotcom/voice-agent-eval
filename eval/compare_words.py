"""Addenda A1 and A2: the word-rule arms against vad-think, run1 + run2 (run score.py on both folders first).

  python -X utf8 eval/compare_words.py         -> eval/results/words_vs_base.md (A1: vad-think-words)
  python -X utf8 eval/compare_words.py --lang  -> eval/results/lang_vs_base.md  (A2: adds vad-think-words-lang)
  python -X utf8 eval/compare_words.py --dur   -> eval/results/dur_vs_base.md   (A3: adds vad-think-words-dur)
  python -X utf8 eval/compare_words.py --pause -> eval/results/pause_vs_base.md (A4: vad-think-pause against
                                                  vad-think-words-dur and vad-think)
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, RUNS, attribute, med, pctl, strict  # noqa: E402

BASE = "vad-think"
BABBLE = {"N05", "N06", "N07", "N08"}


def load(arms):
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {}
    for r in RUNS:
        for a in (*arms, "oracle"):
            f = RES / r / f"{a}.jsonl"
            tr[(r, a)] = {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}
    return sc, tr


def key(x):
    return x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"


PAUSE = "vad-think-pause"
DUR_RULE = ("vad-think-words-dur", PAUSE)       # arms judged with the 0.5 s minimum as well


def seg_at(t, onset):
    return next((s for s in t["user_segments"] if s["start"] - 0.35 <= onset <= s["end"]), None)


def pause_rows(tr):
    """One row per pause of the pause arm: (run, item, role, record, user segment)."""
    rows = []
    for r in RUNS:
        for iid, t in tr[(r, PAUSE)].items():
            for b in t["barge_ins"]:
                if b.get("by") == "pause":
                    s = seg_at(t, b["onset_vad"])
                    rows.append((r, iid, s["role"] if s else "noise", b, s))
    return rows


def main(lang=False, dur=False, pause=False):
    if pause:
        news = ["vad-think-words-dur", PAUSE]
    else:
        news = ["vad-think-words"] + (["vad-think-words-lang"] if lang else []) + (["vad-think-words-dur"] if dur else [])
    arms = [BASE, *news]
    sc, tr = load(arms)
    if pause:
        out = ["# Pause first: vad-think-pause against vad-think-words-dur and vad-think "
               "(generated by eval/compare_words.py --pause)", "",
               "Each arm: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addenda A1, A3 and A4. "
               "A pause counts as a stop, as the frozen scoring rule has it.", ""]
    elif dur:
        out = ["# Barge-in by words and a 0.5 s minimum: vad-think-words-dur against vad-think-words and "
               "vad-think (generated by eval/compare_words.py --dur)", "",
               "Each arm: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addenda A1 and A3.", ""]
    elif lang:
        out = ["# Barge-in by words, recognizer language fixed: vad-think-words-lang against vad-think-words and "
               "vad-think (generated by eval/compare_words.py --lang)", "",
               "Each arm: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addenda A1 and A2.", ""]
    else:
        out = ["# Barge-in by words: vad-think-words against vad-think (generated by eval/compare_words.py)", "",
               "Both arms: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addendum A1.", ""]
    out += ["## Pass counts per run", "", "| Arm | Run | Task | Interaction | Strict |", "|---|---|---|---|---|"]
    for a in arms:
        for r in RUNS:
            rows = sc[r][a]
            inter = [x["interaction_pass"] for x in rows if x.get("interaction_pass") is not None]
            out.append(f"| {a} | {r} | {sum(bool(x['task_pass']) for x in rows)} | {sum(inter)}/{len(inter)} | "
                       f"{sum(strict(x) for x in rows)} |")
    cats = ["task", "pause", "interrupt", "backchannel", "noise-pink", "noise-babble"]
    out += ["", "## Strict pass by category (run1 + run2)", "", "| Arm | " + " | ".join(cats) + " |",
            "|---|" + "---|" * len(cats)]
    for a in arms:
        cells = []
        for c in cats:
            xs = [x for r in RUNS for x in sc[r][a] if key(x) == c]
            cells.append(f"{sum(strict(x) for x in xs)}/{len(xs)}")
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out += ["", "## Turn-taking", "", "| Measure | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    m = {}
    for a in arms:
        rows = [x for r in RUNS for x in sc[r][a]]
        bc = [x for x in rows if x["cat"] == "backchannel" and x.get("overlap")]
        it = [x for x in rows if x["cat"] == "interrupt" and x.get("overlap")]
        stops = [x["stop_latency"] for x in it if "stop_latency" in x]
        qa = [x for x in it if "quiet_after" in x.get("interaction", {})]
        bab = [tr[(r, a)][x["item"]] for r in RUNS for x in sc[r][a] if x["noise"] == "babble"]
        lat = [l for x in rows if x["cat"] == "task" for l in x.get("latency", [])
               if l["role"] == "request" and l.get("first_audio") is not None]
        m[a] = {
            "Backchannels: agent kept talking": f"{sum(bool(x['interaction'].get('kept_talking')) for x in bc)} of {len(bc)}",
            "Interruptions: agent stopped": f"{sum(bool(x['interaction'].get('stopped')) for x in it)} of {len(it)}",
            "Stop latency, median (s)": med(stops),
            "Stop latency, max (s)": max(stops) if stops else None,
            "Quiet within 3 s after a stop request": f"{sum(bool(x['interaction']['quiet_after']) for x in qa)} of {len(qa)}",
            "Babble items with a stop": f"{sum(1 for t in bab if t.get('barge_ins'))} of {len(bab)}",
            "Clean tasks: first audio median (s)": med([l["first_audio"] for l in lat]),
            "Clean tasks: first audio p90 (s)": pctl([l["first_audio"] for l in lat], 0.9),
        }
    if pause:
        prs = pause_rows(tr)
        bc = [x for x in prs if x[2] == "backchannel"]
        it = [x for x in prs if x[2] == "interrupt"]
        bab = [x for x in prs if x[1] in BABBLE]
        res = [x for x in bc if x[3].get("decision") == "resume"]
        gaps = [x[3]["gap"] for x in res if "gap" in x[3]]
        extra = {
            "Backchannels: paused reply resumed (A4)": f"{len(res)} of {len(bc)}",
            "Backchannels: silence while paused, median (s) (A4)": med(gaps),
            "Backchannels: silence while paused, range (s) (A4)": f"{min(gaps):.2f}-{max(gaps):.2f}" if gaps else None,
            "Interruptions: paused reply resumed (A4, wrong)": f"{sum(x[3].get('decision') == 'resume' for x in it)} of {len(it)}",
            "Babble: pauses, resumed / cancelled (A4)": f"{len(bab)}: {sum(x[3].get('decision') == 'resume' for x in bab)}"
                                                        f" / {sum(x[3].get('decision') == 'stop' for x in bab)}",
        }
        for a in arms:
            m[a].update({k: (v if a == PAUSE else "-") for k, v in extra.items()})
    for k in m[BASE]:
        out.append(f"| {k} | " + " | ".join(str(m[a][k]) for a in arms) + " |")

    out += ["", "## Seconds from the start of the user's words to the agent's stop", "",
            "Interruptions (I) and backchannels (B); blank: the agent did not stop."
            + (" vad-think-pause: the moment the agent paused." if pause else ""), "",
            "| Item | " + " | ".join(f"{a} {r}" for a in arms for r in RUNS) + " |", "|---|" + "---|" * (2 * len(arms))]
    for iid in ["I01", "I02", "I03", "I04", "I05", "I06", "I07", "I08", "B01", "B02", "B03", "B04"]:
        cells = []
        for a in arms:
            for r in RUNS:
                t = tr[(r, a)][iid]
                seg = next(s for s in t["user_segments"] if s["role"] in ("interrupt", "backchannel"))
                b = next((b for b in t["barge_ins"] if seg["start"] - 0.05 <= b["t_detect"] <= seg["end"] + 1.0), None)
                cells.append(f"{b['t_detect'] - seg['start']:.2f}" if b else "")
        out.append(f"| {iid} | " + " | ".join(cells) + " |")

    for new in news:
        out += ["", f"## What the words rule heard ({new})", "",
                "Each held stretch of user speech: the last read and the decision.", "",
                "| Run | Item | Role | Last read | Units | Decision | Reads | Onset -> decision (s) |",
                "|---|---|---|---|---|---|---|---|"]
        for r in RUNS:
            for iid, t in tr[(r, new)].items():
                for h in t.get("held", []):
                    role = next((s["role"] for s in t["user_segments"] if s["start"] - 0.35 <= h["onset"] <= s["end"]), "noise")
                    out.append(f"| {r} | {iid} | {role} | {h['text'] or '(empty)'} | {h['units']} | {h['decision']} | "
                               f"{len(h['checks'])} | {round(h['t_decide'] - h['onset'], 2)} |"
                               + (f" voiced {h['speech']:.2f} s |" if new in DUR_RULE else ""))

    if pause:
        out += ["", f"## Every pause ({PAUSE})", "",
                "Paused: seconds from the start of the user's words (or the noise) to the pause. "
                "Silence: seconds from the pause to the resume.", "",
                "| Run | Item | Role | Paused (s) | Heard before the pause | Last read | Decision | Silence (s) |",
                "|---|---|---|---|---|---|---|---|"]
        for r, iid, role, b, s in pause_rows(tr):
            since = f"{b['t_detect'] - s['start']:.2f}" if s else f"at {b['t_detect']:.2f}"
            out.append(f"| {r} | {iid} | {role} | {since} | {b['heard'] or '(between chunks)'} | {b.get('text') or '(empty)'} | "
                       f"{b.get('decision', 'unresolved')} | {b['gap'] if 'gap' in b else ''} |")

    out += ["", "## Failed item-runs and their cause (preregistered order)", "", "| Arm | Run | Item | Cause |", "|---|---|---|---|"]
    orc = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            orc.setdefault(x["item"], []).append(x)
    for a in arms:
        for r in RUNS:
            for x in sc[r][a]:
                if not strict(x):
                    out.append(f"| {a} | {r} | {x['item']} | {attribute(x, tr[(r, a)][x['item']], orc)} |")

    out.append("")
    for new in news:
        cost = 0.0
        for r in RUNS:
            u = json.loads((RES / r / f"{new}.usage.json").read_text(encoding="utf-8"))
            cost += u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6
        out.append(f"Model cost of the two {new} runs: {cost:.3f} USD.")
    out.append("")
    name = ("pause_vs_base.md" if pause else "dur_vs_base.md" if dur else "lang_vs_base.md" if lang
            else "words_vs_base.md")
    (RES / name).write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main(lang="--lang" in sys.argv, dur="--dur" in sys.argv, pause="--pause" in sys.argv)
