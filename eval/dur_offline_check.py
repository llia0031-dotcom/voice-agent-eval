"""Offline estimate for addendum A3 (no model calls): how much voiced time Silero VAD finds in each backchannel
and interruption clip, and whether it reaches the 0.5 s minimum. Not a substitute for the scored run: the VAD
starts from a reset state here, and the clip is placed at four sub-frame offsets instead of where the agent's
reply puts it.

  python -X utf8 eval/dur_offline_check.py  -> eval/results/dur_offline_check.md
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "agent"))
sys.path.insert(0, str(ROOT / "eval"))
from config import ARMS, FRAME, SR, START_SECS, VAD_OFF, VAD_ON  # noqa: E402
from run import load_items  # noqa: E402
from audio import SileroVAD  # noqa: E402

FDUR = FRAME / SR
MIN_SPEECH = ARMS["vad-think-words-dur"]["barge_min_speech"]
ENDPOINT = ARMS["vad-think-words-dur"]["endpoint_silence"]
ITEMS = ["B01", "B02", "B03", "B04", "I01", "I02", "I03", "I04", "I05", "I06", "I07", "I08"]


def voiced(vad, clip, offset):
    """Voiced seconds of the held stretch as pipeline.py counts them, and seconds from clip start to 0.5 s."""
    vad.reset()
    x = np.concatenate([np.zeros(int(1.0 * SR) + offset, np.float32), clip, np.zeros(int(1.5 * SR), np.float32)])
    speech, run, sil, onset_t, total, reach = False, 0.0, 0.0, None, 0.0, None
    for f in range(len(x) // FRAME):
        p = vad(x[f * FRAME:(f + 1) * FRAME])
        speech = True if p >= VAD_ON else False if p < VAD_OFF else speech
        t = (f + 1) * FDUR
        run, sil = (run + FDUR, 0.0) if speech else (0.0, sil + FDUR)
        if onset_t is None:
            if speech and run >= START_SECS - 1e-9:
                onset_t, total = t - run, run
        else:
            total += FDUR if speech else 0.0
            if not speech and sil >= ENDPOINT - 1e-9:
                break
        if onset_t is not None and reach is None and total + 1e-9 >= MIN_SPEECH:
            reach = t - (1.0 + offset / SR)
    return total if onset_t is not None else 0.0, reach


def main():
    items = {c["id"]: c for c in load_items(ROOT / "eval" / "cases.json", set(ITEMS))}
    vad = SileroVAD()
    out = ["# Voiced time per clip, offline estimate for addendum A3 (generated by eval/dur_offline_check.py)", "",
           f"Silero VAD with the run's thresholds; a clip counts as an interruption only after {MIN_SPEECH} s of voiced "
           "time. Four sub-frame offsets (0, 8, 16, 24 ms). No model calls; not the scored run.", "",
           "| Item | Words | Clip (s) | Voiced (s), four offsets | Reaches 0.5 s | Seconds from clip start to 0.5 s voiced |",
           "|---|---|---|---|---|---|"]
    for iid in ITEMS:
        seg = next(s for s in items[iid]["segments"] if s["role"] in ("interrupt", "backchannel"))
        res = [voiced(vad, seg["audio"], int(ms * SR / 1000)) for ms in (0, 8, 16, 24)]
        reached = sum(1 for _, r in res if r is not None)
        times = [f"{r:.2f}" for _, r in res if r is not None]
        out.append(f"| {iid} | {seg['text']} | {len(seg['audio']) / SR:.2f} | "
                   + " / ".join(f"{v:.2f}" for v, _ in res) + f" | {reached} of 4 | {' / '.join(times) or '—'} |")
    (ROOT / "eval" / "results" / "dur_offline_check.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
