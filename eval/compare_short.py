"""Addendum A5: a shorter first speech chunk (vad-think-short) against vad-think, run1 + run2
(run score.py on both folders first).

  python -X utf8 eval/compare_short.py  -> eval/results/short_vs_base.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, RUNS, attribute, med, pctl, strict  # noqa: E402

BASE, NEW = "vad-think", "vad-think-short"
ARMS = [BASE, NEW]


def load():
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {}
    for r in RUNS:
        for a in (*ARMS, "oracle"):
            f = RES / r / f"{a}.jsonl"
            tr[(r, a)] = {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}
    return sc, tr


def clean(sc, r, a):
    return [x for x in sc[r][a] if x["cat"] == "task"]


def first_reply(t):
    """Pieces of the first spoken reply step of the first response, in order (played or not)."""
    ps = sorted((p for p in t["pieces"] if p["resp"] == 0), key=lambda p: p["start"])
    return [p for p in ps if p["step"] == ps[0]["step"]] if ps else []


def main():
    sc, tr = load()
    out = ["# Shorter first speech chunk: vad-think-short against vad-think (generated by eval/compare_short.py)", "",
           "Both arms: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addendum A5.", "",
           "## Pass counts per run", "", "| Arm | Run | Task | Interaction | Strict |", "|---|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            rows = sc[r][a]
            inter = [x["interaction_pass"] for x in rows if x.get("interaction_pass") is not None]
            out.append(f"| {a} | {r} | {sum(bool(x['task_pass']) for x in rows)} | {sum(inter)}/{len(inter)} | "
                       f"{sum(strict(x) for x in rows)} |")
    cats = ["task", "pause", "interrupt", "backchannel", "noise-pink", "noise-babble"]
    key = lambda x: x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"
    out += ["", "## Strict pass by category (run1 + run2)", "", "| Arm | " + " | ".join(cats) + " |",
            "|---|" + "---|" * len(cats)]
    for a in ARMS:
        cells = []
        for c in cats:
            xs = [x for r in RUNS for x in sc[r][a] if key(x) == c]
            cells.append(f"{sum(strict(x) for x in xs)}/{len(xs)}")
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out += ["", "## Latency, clean task items, first user turn (seconds)", "",
            "Parts are medians of each part, so they do not add up exactly.", "",
            "| Arm | Runs | n | First audio median | p90 | Answer audio median | Turn-end wait | Recognition | "
            "Model to first speech chunk | First chunk synthesis |", "|---|---|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        for runs in (RUNS, ["run1"], ["run2"]):
            L = [l for r in runs for x in clean(sc, r, a) for l in x.get("latency", [])
                 if l["role"] == "request" and l.get("first_audio") is not None]
            f = [l["first_audio"] for l in L]
            ans = [l["answer_audio"] for l in L if l.get("answer_audio") is not None]
            out.append(f"| {a} | {' + '.join(runs)} | {len(L)} | {med(f)} | {pctl(f, 0.9)} | {med(ans)} | "
                       f"{med([l['endpoint_wait'] for l in L])} | {med([l['asr'] for l in L])} | "
                       f"{med([l['llm'] for l in L])} | {med([l['tts'] for l in L])} |")

    out += ["", "## The first spoken reply step of each clean task item (run1 + run2)", "",
            "First chunk: the first piece of speech. Gap: silence between the end of the first piece and the start of "
            "the second piece of the same step (steps with one piece have no gap).", "",
            "| Arm | n | First chunk, median characters | p90 | First chunks of 4 characters or fewer | "
            "Steps with a second piece | Gap median (s) | Gaps over 0.3 s | Longest gap (s) |",
            "|---|---|---|---|---|---|---|---|---|"]
    examples = {}
    for a in ARMS:
        lens, gaps = [], []
        for r in RUNS:
            for x in clean(sc, r, a):
                ps = first_reply(tr[(r, a)][x["item"]])
                if not ps:
                    continue
                lens.append(len(ps[0]["text"].strip()))
                examples.setdefault(a, []).append(ps[0]["text"])
                if len(ps) > 1:
                    gaps.append(round(ps[1]["start"] - ps[0]["full_end"], 3))
        out.append(f"| {a} | {len(lens)} | {med(lens)} | {pctl(lens, 0.9)} | {sum(n <= 4 for n in lens)} | "
                   f"{len(gaps)} | {med(gaps)} | {sum(g > 0.3 for g in gaps)} | {max(gaps) if gaps else None} |")
    out += ["", "First chunks of the new arm, run1 then run2:", "",
            "; ".join(f"「{t.strip()}」" for t in examples.get(NEW, []))]

    out += ["", "## Where the new rule made the first chunk short", "",
            "Item-runs of the new arm whose first chunk has 4 characters or fewer or ends at a colon, against the same "
            "item and run of vad-think (clean task items, first turn).", "",
            "| Run | Item | First chunk | vad-think first chunk | Synthesis (s) | vad-think synthesis (s) | Saved (s) | "
            "First audio (s) | vad-think first audio (s) | Gap after the first chunk (s) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    saved = []
    for r in RUNS:
        lat = {a: {x["item"]: next((l for l in x.get("latency", []) if l["role"] == "request"
                                     and l.get("first_audio") is not None), None) for x in clean(sc, r, a)} for a in ARMS}
        for x in clean(sc, r, NEW):
            ps = first_reply(tr[(r, NEW)][x["item"]])
            if not ps:
                continue
            c = ps[0]["text"].strip()
            if not (len(c) <= 4 or c.endswith("：") or c.endswith(":")):
                continue
            bp = first_reply(tr[(r, BASE)][x["item"]])
            ln, lb = lat[NEW][x["item"]], lat[BASE][x["item"]]
            gap = round(ps[1]["start"] - ps[0]["full_end"], 2) if len(ps) > 1 else None
            saved.append(round(lb["tts"] - ln["tts"], 3))
            out.append(f"| {r} | {x['item']} | {c} | {bp[0]['text'].strip() if bp else ''} | {ln['tts']} | {lb['tts']} | "
                       f"{saved[-1]} | {ln['first_audio']} | {lb['first_audio']} | {gap} |")
    if saved:
        out += ["", f"Synthesis saved: {min(saved):.3f} to {max(saved):.3f} s, median {med(saved)} s, over {len(saved)} item-runs."]

    out += ["", "## Turn-taking (run1 + run2)", "", "| Measure | " + " | ".join(ARMS) + " |", "|---|---|---|"]
    m = {}
    for a in ARMS:
        rows = [x for r in RUNS for x in sc[r][a]]
        bc = [x for x in rows if x["cat"] == "backchannel" and x.get("overlap")]
        it = [x for x in rows if x["cat"] == "interrupt" and x.get("overlap")]
        stops = [x["stop_latency"] for x in it if "stop_latency" in x]
        m[a] = {"Backchannels: agent kept talking": f"{sum(bool(x['interaction'].get('kept_talking')) for x in bc)} of {len(bc)}",
                "Interruptions: agent stopped": f"{sum(bool(x['interaction'].get('stopped')) for x in it)} of {len(it)}",
                "Stop latency, median (s)": med(stops)}
    for k in m[BASE]:
        out.append(f"| {k} | " + " | ".join(str(m[a][k]) for a in ARMS) + " |")

    out += ["", "## Failed item-runs and their cause (preregistered order)", "", "| Arm | Run | Item | Cause |", "|---|---|---|---|"]
    orc = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            orc.setdefault(x["item"], []).append(x)
    for a in ARMS:
        for r in RUNS:
            for x in sc[r][a]:
                if not strict(x):
                    out.append(f"| {a} | {r} | {x['item']} | {attribute(x, tr[(r, a)][x['item']], orc)} |")
    cost = 0.0
    for r in RUNS:
        u = json.loads((RES / r / f"{NEW}.usage.json").read_text(encoding="utf-8"))
        cost += u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6
    out += ["", f"Model cost of the two {NEW} runs: {cost:.3f} USD.", ""]
    (RES / "short_vs_base.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
