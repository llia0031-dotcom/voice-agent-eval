"""Addendum A12: disfluent requests and new voices (eval/disfluent_cases.json), vad-think, vad-think-combo and the
text-only control, two runs (results/dis1, dis2; score with --cases eval/disfluent_cases.json first).

  python -X utf8 eval/compare_disfluent.py  -> eval/results/disfluent_vs_base.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, ROOT, med, strict  # noqa: E402

ARMS = ["vad-think", "vad-think-combo", "oracle"]
RUNS = ["dis1", "dis2"]
SOURCE = {"V01": "T01", "V02": "T02", "V03": "T05", "V04": "T11"}


def traces(folder, arm):
    f = RES / folder / f"{arm}.jsonl"
    return {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}


def main():
    cases = {c["id"]: c for c in json.loads((ROOT / "eval" / "disfluent_cases.json").read_text(encoding="utf-8"))["items"]}
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {(r, a): traces(r, a) for r in RUNS for a in ARMS}
    out = ["# Disfluent requests and new voices (generated by eval/compare_disfluent.py)", "",
           "Rules: eval/PREREGISTRATION.md addendum A12. 14 items (eval/disfluent_cases.json), two runs each.", "",
           "| Arm | Run | Disfluent items passed (of 10) | New-voice items passed (of 4) | Strict (of 14) |",
           "|---|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            xs = sc[r][a]
            d = sum(bool(x["task_pass"]) for x in xs if x["item"].startswith("D"))
            v = sum(bool(x["task_pass"]) for x in xs if x["item"].startswith("V"))
            out.append(f"| {a} | {r} | {d} | {v} | {sum(strict(x) for x in xs)} |")

    out += ["", "## Turn ends inside a request", "",
            "A turn end detected before the request's audio was over (the user had paused inside it), and whether a "
            "reply then played before the request ended.", "",
            "| Arm | Item-runs with a turn end inside the request | Of those, a reply played inside the request |",
            "|---|---|---|"]
    early = {}
    for a in ARMS[:2]:
        n = played = 0
        rows = []
        for r in RUNS:
            for iid, t in tr[(r, a)].items():
                req = next(s for s in t["user_segments"] if s["role"] == "request")
                ends = [x["t_endpoint"] for x in t["responses"] if x["t_endpoint"] < req["end"] - 0.05]
                if ends:
                    n += 1
                    p = any(pc["end"] > pc["start"] and pc["start"] < req["end"] for pc in t["pieces"])
                    played += p
                    rows.append(f"{r} {iid}")
        early[a] = rows
        out.append(f"| {a} | {n} of {len(RUNS) * len(cases)}: {', '.join(rows) or 'none'} | {played} |")

    out += ["", "## What each item was meant to say and what the recognizer heard (first answered turn)", "",
            "| Item | Kind | Request | " + " | ".join(f"{a} {r}" for a in ARMS[:2] for r in RUNS) + " | Passed (vad-think, combo, oracle; run1 / run2) |",
            "|---|---|---|---|---|---|---|---|"]
    for iid, c in cases.items():
        cells = []
        for a in ARMS[:2]:
            for r in RUNS:
                rs = [x for x in tr[(r, a)][iid]["responses"] if x["status"] == "done"]
                cells.append(rs[0]["asr_text"] if rs else "")
        passed = "; ".join(" / ".join("y" if next(x for x in sc[r][a] if x["item"] == iid)["task_pass"] else "n"
                                      for r in RUNS) for a in ARMS)
        out.append(f"| {iid} | {c['kind']} | {c['segments'][0]['text']} | " + " | ".join(cells) + f" | {passed} |")

    out += ["", "## New voices against the same text in the original voices", "",
            "| Item | Source item | vad-think, new voice (2 runs) | vad-think, original voice (run1 + run2 of the 42) |",
            "|---|---|---|---|"]
    base = {r: {x["item"]: x for x in json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"]["vad-think"]}
            for r in ["run1", "run2"]}
    for v, t in SOURCE.items():
        new = sum(bool(next(x for x in sc[r]["vad-think"] if x["item"] == v)["task_pass"]) for r in RUNS)
        old = sum(bool(base[r][t]["task_pass"]) for r in ["run1", "run2"])
        out.append(f"| {v} | {t} | {new} of 2 | {old} of 2 |")

    lat = {}
    for a in ARMS[:2]:
        fa = [l["first_audio"] for r in RUNS for x in sc[r][a] for l in x.get("latency", [])
              if l["role"] == "request" and l.get("first_audio") is not None]
        lat[a] = med(fa)
    out += ["", "First audio after the request, median (s): " + "; ".join(f"{a} {lat[a]}" for a in ARMS[:2]) + "."]
    cost = {}
    for a in ARMS:
        c = 0.0
        for r in RUNS:
            f = RES / r / f"{a}.usage.json"
            if f.exists():
                u = json.loads(f.read_text(encoding="utf-8"))
                c += u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6
        cost[a] = c
    out += ["", "Model cost, two runs: " + "; ".join(f"{a} {cost[a]:.3f} USD" for a in ARMS) + ".", ""]
    (RES / "disfluent_vs_base.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
