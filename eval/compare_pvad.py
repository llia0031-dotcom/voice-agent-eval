"""Addendum A7: FireRedChat pVAD instead of Silero (vad-think-pvad) against vad-think, run1 + run2
(run score.py on both folders first).

  python -X utf8 eval/compare_pvad.py  -> eval/results/pvad_vs_base.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, RUNS, attribute, med, pctl, strict  # noqa: E402

BASE, NEW = "vad-think", "vad-think-pvad"
ARMS = [BASE, NEW]


def main():
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {}
    for r in RUNS:
        for a in (*ARMS, "oracle"):
            f = RES / r / f"{a}.jsonl"
            tr[(r, a)] = {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}
    out = ["# Listening only to the first speaker: vad-think-pvad against vad-think (generated by eval/compare_pvad.py)", "",
           "Both arms: run1 + run2, 42 items each. Rules: eval/PREREGISTRATION.md addendum A7.", "",
           "## Pass counts per run", "", "| Arm | Run | Task | Interaction | Strict |", "|---|---|---|---|---|"]
    for a in ARMS:
        for r in RUNS:
            rows = sc[r][a]
            inter = [x["interaction_pass"] for x in rows if x.get("interaction_pass") is not None]
            out.append(f"| {a} | {r} | {sum(bool(x['task_pass']) for x in rows)} | {sum(inter)}/{len(inter)} | "
                       f"{sum(strict(x) for x in rows)} |")
    cats = ["task", "pause", "interrupt", "backchannel", "noise-pink", "noise-babble"]
    key = lambda x: x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"
    out += ["", "## Strict pass by category (run1 + run2)", "", "| Arm | " + " | ".join(cats) + " |",
            "|---|" + "---|" * len(cats)]
    for a in ARMS:
        cells = []
        for c in cats:
            xs = [x for r in RUNS for x in sc[r][a] if key(x) == c]
            cells.append(f"{sum(strict(x) for x in xs)}/{len(xs)}")
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out += ["", "## Noise items (run1 + run2)", "",
            "| Arm | Noise | Item-runs | First turn forced at the 20 s cap | Agent stopped mid-reply | Task pass | "
            "First audio median (s) | First audio p90 (s) | Turn-end wait median (s) | Model to first chunk median (s) | "
            "First chunk synthesis median (s) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        for kind in ["pink", "babble"]:
            xs = [(r, x) for r in RUNS for x in sc[r][a] if x["noise"] == kind]
            forced = sum(any(e["ev"] == "forced_endpoint" for e in tr[(r, a)][x["item"]]["events"]) for r, x in xs)
            stops = sum(bool(tr[(r, a)][x["item"]]["barge_ins"]) for r, x in xs)
            L = [l for _, x in xs for l in x.get("latency", []) if l["role"] == "request" and l.get("first_audio") is not None]
            fa = [l["first_audio"] for l in L]
            out.append(f"| {a} | {kind} | {len(xs)} | {forced} | {stops} | {sum(bool(x['task_pass']) for _, x in xs)} | "
                       f"{med(fa)} | {pctl(fa, 0.9)} | {med([l['endpoint_wait'] for l in L])} | {med([l['llm'] for l in L])} | "
                       f"{med([l['tts'] for l in L])} |")
    out += ["", "What the recognizer heard as the first request of each babble item:", "",
            "| Run | Item | " + " | ".join(ARMS) + " |", "|---|---|---|---|"]
    for r in RUNS:
        for iid in ["N05", "N06", "N07", "N08"]:
            cells = []
            for a in ARMS:
                rs = [x for x in tr[(r, a)][iid]["responses"] if x["status"] == "done"]
                cells.append(rs[0]["asr_text"] if rs else "")
            out.append(f"| {r} | {iid} | " + " | ".join(cells) + " |")

    out += ["", "## Turn-taking and latency (run1 + run2)", "", "| Measure | " + " | ".join(ARMS) + " |", "|---|---|---|"]
    m = {}
    for a in ARMS:
        rows = [x for r in RUNS for x in sc[r][a]]
        bc = [x for x in rows if x["cat"] == "backchannel" and x.get("overlap")]
        it = [x for x in rows if x["cat"] == "interrupt" and x.get("overlap")]
        pz = [x for x in rows if x["cat"] == "pause"]
        stops = [x["stop_latency"] for x in it if "stop_latency" in x]
        lat = [l for x in rows if x["cat"] == "task" for l in x.get("latency", [])
               if l["role"] == "request" and l.get("first_audio") is not None]
        m[a] = {"Interruptions: agent stopped": f"{sum(bool(x['interaction'].get('stopped')) for x in it)} of {len(it)}",
                "Stop latency, median (s)": med(stops), "Stop latency, max (s)": max(stops) if stops else None,
                "Backchannels: agent kept talking": f"{sum(bool(x['interaction'].get('kept_talking')) for x in bc)} of {len(bc)}",
                "Pauses: no speech inside the pause": f"{sum(bool(x['interaction'].get('no_takeover_in_pause')) for x in pz)} of {len(pz)}",
                "Pauses: reply started inside the pause": f"{sum(bool(x.get('premature_llm')) for x in pz)} of {len(pz)}",
                "Clean tasks: first audio median (s)": med([l["first_audio"] for l in lat]),
                "Clean tasks: first audio p90 (s)": pctl([l["first_audio"] for l in lat], 0.9)}
    for k in m[BASE]:
        out.append(f"| {k} | " + " | ".join(str(m[a][k]) for a in ARMS) + " |")

    out += ["", "## Failed item-runs and their cause (preregistered order)", "", "| Arm | Run | Item | Cause |", "|---|---|---|---|"]
    orc = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            orc.setdefault(x["item"], []).append(x)
    for a in ARMS:
        for r in RUNS:
            for x in sc[r][a]:
                if not strict(x):
                    out.append(f"| {a} | {r} | {x['item']} | {attribute(x, tr[(r, a)][x['item']], orc)} |")
    cost = 0.0
    for r in RUNS:
        u = json.loads((RES / r / f"{NEW}.usage.json").read_text(encoding="utf-8"))
        cost += u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6
    out += ["", f"Model cost of the two {NEW} runs: {cost:.3f} USD.", ""]
    (RES / "pvad_vs_base.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
