"""Addendum A8: the four changes that helped, together (vad-think-combo), against vad-think and each change alone.

Needs scores for results/run1, run2 (42 items) and results/confirm1, confirm2 (the four confirmation items,
scored with --cases eval/confirm_cases.json).

  python -X utf8 eval/compare_combo.py  -> eval/results/combo_vs_base.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tables import PRICE_IN, PRICE_OUT, RES, RUNS, attribute, med, strict  # noqa: E402
from compare_confirm import cancels  # noqa: E402

BASE, NEW = "vad-think", "vad-think-combo"
ARMS = [BASE, "vad-think-short", "vad-think-confirm", "vad-think-pvad", "vad-think-pause", NEW]
CRUNS = ["confirm1", "confirm2"]
CONFIRM_ARMS = [BASE, "vad-think-confirm", NEW]


def traces(folder, arm):
    f = RES / folder / f"{arm}.jsonl"
    return {json.loads(x)["item"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()}


def main():
    sc = {r: json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"] for r in RUNS}
    tr = {(r, a): traces(r, a) for r in RUNS for a in (*ARMS, "oracle")}
    rows = {}
    for a in ARMS:
        xs = [(r, x) for r in RUNS for x in sc[r][a]]
        bab = [(r, x) for r, x in xs if x["noise"] == "babble"]
        it = [x for _, x in xs if x["cat"] == "interrupt" and x.get("overlap")]
        stops = [x["stop_latency"] for x in it if "stop_latency" in x]
        bc = [(r, x) for r, x in xs if x["cat"] == "backchannel" and x.get("overlap")]
        survived = 0
        for r, x in bc:
            t = tr[(r, a)][x["item"]]
            seg = next(s for s in t["user_segments"] if s["role"] == "backchannel")
            b = next((b for b in t["barge_ins"] if seg["start"] - 0.05 <= b["t_detect"] <= seg["end"] + 1.0), None)
            survived += b is None or b.get("decision") == "resume"
        lat = [l for _, x in xs if x["cat"] == "task" for l in x.get("latency", [])
               if l["role"] == "request" and l.get("first_audio") is not None]
        bl = [l for _, x in bab for l in x.get("latency", []) if l["role"] == "request" and l.get("first_audio") is not None]
        item = lambda iid, r: next(x for x in sc[r][a] if x["item"] == iid)
        rows[a] = {
            "Strict pass, run1 / run2 (of 42)": " / ".join(str(sum(strict(x) for x in sc[r][a])) for r in RUNS),
            "Clean tasks: first audio median (s)": med([l["first_audio"] for l in lat]),
            "Clean tasks: first chunk synthesis median (s)": med([l["tts"] for l in lat]),
            "Babble: first turn forced at the 20 s cap": f"{sum(any(e['ev'] == 'forced_endpoint' for e in tr[(r, a)][x['item']]['events']) for r, x in bab)} of {len(bab)}",
            "Babble: agent stopped mid-reply": f"{sum(bool(tr[(r, a)][x['item']]['barge_ins']) for r, x in bab)} of {len(bab)}",
            "Babble: first audio median (s)": med([l["first_audio"] for l in bl]),
            "Interruptions: stopped (or paused)": f"{sum(bool(x['interaction'].get('stopped')) for x in it)} of {len(it)}",
            "Interruptions: stop latency median (s)": med(stops),
            "Interruptions: stop latency max (s)": max(stops) if stops else None,
            "Backchannels: kept talking (frozen rule)": f"{sum(bool(x['interaction'].get('kept_talking')) for _, x in bc)} of {len(bc)}",
            "Backchannels: reply survived (kept talking or resumed)": f"{survived} of {len(bc)}",
            "I05 (cancel, then wait): strict run1 / run2": " / ".join("pass" if strict(item("I05", r)) else "fail" for r in RUNS),
            "T04 (cancel, no answer): strict run1 / run2": " / ".join("pass" if strict(item("T04", r)) else "fail" for r in RUNS),
        }
    out = ["# The four changes together: vad-think-combo against vad-think and each change alone "
           "(generated by eval/compare_combo.py)", "",
           "Rules: eval/PREREGISTRATION.md addendum A8. Every arm: run1 + run2 of the 42 items.", "",
           "| Measure | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    for k in rows[BASE]:
        out.append(f"| {k} | " + " | ".join(str(rows[a][k]) for a in ARMS) + " |")

    cats = ["task", "pause", "interrupt", "backchannel", "noise-pink", "noise-babble"]
    key = lambda x: x["cat"] if x["cat"] != "noise" else f"noise-{x['noise']}"
    out += ["", "## Strict pass by category (run1 + run2)", "", "| Arm | " + " | ".join(cats) + " |",
            "|---|" + "---|" * len(cats)]
    for a in (BASE, NEW):
        cells = [f"{sum(strict(x) for r in RUNS for x in sc[r][a] if key(x) == c)}/"
                 f"{sum(1 for r in RUNS for x in sc[r][a] if key(x) == c)}" for c in cats]
        out.append(f"| {a} | " + " | ".join(cells) + " |")

    out += ["", f"## Every pause in {NEW}", "", "| Run | Item | Role | Paused after (s) | Decision | Silence (s) |",
            "|---|---|---|---|---|---|"]
    wrong = 0
    for r in RUNS:
        for iid, t in tr[(r, NEW)].items():
            for b in t["barge_ins"]:
                if b.get("by") != "pause":
                    continue
                s = next((s for s in t["user_segments"] if s["start"] - 0.35 <= b["onset_vad"] <= s["end"]), None)
                role = s["role"] if s else "noise"
                wrong += role == "interrupt" and b.get("decision") == "resume"
                out.append(f"| {r} | {iid} | {role} | {(b['t_detect'] - s['start']) if s else b['t_detect']:.2f} | "
                           f"{b.get('decision', 'unresolved')} | {b.get('gap', '')} |")
    out += ["", f"Interruptions resumed by mistake: {wrong}."]

    out += ["", "## The four confirmation items (confirm1 + confirm2)", "",
            "| Arm | Task pass | Asked first | Cancel time median (s) |", "|---|---|---|---|"]
    for a in CONFIRM_ARMS:
        n = ok = asked = 0
        times = []
        for r in CRUNS:
            csc = {x["item"]: x for x in json.loads((RES / r / "scores.json").read_text(encoding="utf-8"))["items"][a]}
            for iid, t in traces(r, a).items():
                segs = {s["role"]: s for s in t["user_segments"]}
                c = cancels(t)
                n += 1
                ok += bool(csc[iid]["task_pass"])
                asked += not any("answer" not in segs or at < segs["answer"]["start"] for at, _ in c)
                if c:
                    times.append(round(c[0][0] - segs["request"]["end"], 2))
        out.append(f"| {a} | {ok} of {n} | {asked} of {n} | {med(times)} |")

    out += ["", f"## Failed item-runs of {NEW} and their cause (preregistered order)", "", "| Run | Item | Cause |", "|---|---|---|"]
    orc = {}
    for r in RUNS:
        for x in sc[r]["oracle"]:
            orc.setdefault(x["item"], []).append(x)
    for r in RUNS:
        for x in sc[r][NEW]:
            if not strict(x):
                out.append(f"| {r} | {x['item']} | {attribute(x, tr[(r, NEW)][x['item']], orc)} |")
    cost = 0.0
    for folder in (*RUNS, *CRUNS):
        f = RES / folder / f"{NEW}.usage.json"
        if f.exists():
            u = json.loads(f.read_text(encoding="utf-8"))
            cost += u["input_tokens"] * PRICE_IN / 1e6 + u["output_tokens"] * PRICE_OUT / 1e6
    out += ["", f"Model cost of {NEW} (42 items twice and the four confirmation items twice): {cost:.3f} USD.", ""]
    (RES / "combo_vs_base.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
